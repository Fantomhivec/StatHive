import type { TemplateDto } from "../../bridge/hostApi";

/** Normalize TemplateDto fields for templatesSave IPC. */
export function buildTemplateSavePayload(
  tpl: TemplateDto,
  marketplace: "wb" | "ozon",
  tabName: string,
): TemplateDto {
  return {
    ...tpl,
    marketplace,
    tab_name: tabName,
    spreadsheet_id: tpl.spreadsheet_id ?? "",
    sheet_name: tpl.sheet_name ?? "",
    export_to_excel: !!tpl.export_to_excel,
    spreadsheet_title: tpl.spreadsheet_title ?? "",
    time_triggers: tpl.time_triggers ?? [],
    second_spreadsheet_id: tpl.second_spreadsheet_id ?? "",
    second_sheet_name: tpl.second_sheet_name ?? "",
    second_spreadsheet_title: tpl.second_spreadsheet_title ?? "",
    id_mode: tpl.id_mode ?? "",
    id_source_range: tpl.id_source_range ?? "",
    cabinets_source_range: tpl.cabinets_source_range ?? "",
    nm_id_source_range: tpl.nm_id_source_range ?? "",
    stocks_skus_source_range: tpl.stocks_skus_source_range ?? "",
    id_adv_campaign_source_range: tpl.id_adv_campaign_source_range ?? "",
    offer_id_source_range: tpl.offer_id_source_range ?? "",
    product_id_source_range: tpl.product_id_source_range ?? "",
    sku_source_range: tpl.sku_source_range ?? "",
    content_media_links_source_range: tpl.content_media_links_source_range ?? "",
    subject_id_source_range: tpl.subject_id_source_range ?? "",
    subject_name_source_range: tpl.subject_name_source_range ?? "",
    use_custom_subject_ids: !!tpl.use_custom_subject_ids,
    promotions_all_promo: !!tpl.promotions_all_promo,
    cards_update_dimensions_mode: tpl.cards_update_dimensions_mode !== false,
    cards_update_vendor_code_mode: !!tpl.cards_update_vendor_code_mode,
    cards_update_vat_mode: !!tpl.cards_update_vat_mode,
    cards_update_brand_mode: !!tpl.cards_update_brand_mode,
    cards_update_length_range: tpl.cards_update_length_range ?? "",
    cards_update_width_range: tpl.cards_update_width_range ?? "",
    cards_update_height_range: tpl.cards_update_height_range ?? "",
    cards_update_vendor_code_range: tpl.cards_update_vendor_code_range ?? "",
    cards_update_vat_range: tpl.cards_update_vat_range ?? "",
    cards_update_brand_range: tpl.cards_update_brand_range ?? "",
    subjects_filters: tpl.subjects_filters ?? {
      locale: "ru",
      name: "",
      limit: 30,
      offset: 0,
      parent_id: null,
    },
    date_from: tpl.date_from ?? "",
    date_to: tpl.date_to ?? "",
    date_template_type: tpl.date_template_type ?? "",
    cabinets: tpl.cabinets ?? [],
    sync_settings: tpl.sync_settings ?? {
      enable_change_sync: false,
      key_field_1: "",
      key_field_2: "",
      do_not_delete_old_rows: false,
    },
    write_sort_field_name: tpl.write_sort_field_name ?? "",
    write_sort_direction:
      (tpl.write_sort_direction ?? "asc").toLowerCase() === "desc" ? "desc" : "asc",
    clear_only_written_range: !!tpl.clear_only_written_range,
  };
}
